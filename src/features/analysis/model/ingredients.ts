// Ingredient recognition: splits an ingredient list into individual ingredients (including
// sub-ingredients in brackets) and works out which ones we actually understand, using the
// Open Food Facts ingredient and additive dictionaries (src/features/analysis/data, ODbL),
// label abbreviations and our own extra vocabulary. Anything left over is reported as
// unrecognised, so the app never treats an unknown ingredient as silently fine.
// Measured against real labels by `npm run audit:ingredients` (docs/INGREDIENT-COVERAGE.md).

import { isTraceContext } from '@/shared/lib/text';
import additiveClassesJson from '../data/additive-classes.json';
import additiveNamesJson from '../data/additive-names.json';
import additivesJson from '../data/additives.json';
import ingredientNamesJson from '../data/ingredient-names.json';
import { ABBREVIATIONS } from './abbreviations';
import { CLASS_PHRASES, EXTRA_INGREDIENTS, STOP_WORDS } from './extraVocabulary';
import { FuzzyIndex } from './fuzzy';

const HTML_ENTITY = /&(?:quot|amp|apos|lt|gt|nbsp|#39|#x27);?/gi;

/** Lower-case, accents and HTML entities removed, "&" → "and", punctuation and hyphens → spaces. */
export function normName(s: string): string {
  return s
    .replace(HTML_ENTITY, ' ')
    .toLowerCase()
    .normalize('NFKD')
    .replace(/\p{M}/gu, '')
    .replace(/’/g, "'")
    .replace(/&/g, ' and ')
    .replace(/[^a-z0-9']+/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

const VOCAB = new Set<string>([...ingredientNamesJson, ...EXTRA_INGREDIENTS].map(normName));
const ADDITIVE_BY_NAME = new Map<string, string>(
  Object.entries(additiveNamesJson as Record<string, string>).map(([name, code]) => [normName(name), code]),
);
// Generated by scripts/build-ingredient-data.mjs: { code: [name, classes] }.
const ADDITIVES = additivesJson as unknown as Record<string, [string, string[]]>;
const CLASS_LABELS = additiveClassesJson as Record<string, string>;
// Maps, so label words like "constructor" can't hit Object.prototype.
const ABBR = new Map(Object.entries(ABBREVIATIONS).map(([k, v]) => [normName(k), v]));
const CLASSES = new Set(CLASS_PHRASES.map(normName));
const STOP = new Set(STOP_WORDS);

export interface AdditiveInfo {
  code: string;
  name: string;
  functions: string[];
}

/** Name and functions of an additive code like "e471", or null if unknown. */
export function additiveInfo(code: string): AdditiveInfo | null {
  const entry = ADDITIVES[code] ?? ADDITIVES[code.replace(/[a-h]$/, '')];
  if (!entry) return null;
  return { code, name: entry[0], functions: entry[1].map((c) => CLASS_LABELS[c] ?? c.replace(/-/g, ' ')) };
}

export interface Candidate {
  /** As written on the label (trimmed). */
  text: string;
  /** Cleaned + normalised name used for lookups. */
  name: string;
  start: number;
  end: number;
  /** Index of the top-level ingredient this belongs to. */
  item: number;
}

// ---------- Splitting ----------

/** Back-of-pack text that some databases store inside the ingredient field. */
const NOISE =
  /\b(?:mg|mcg|kcal|kj|www|ltd|limited|pvt|lic|licen[cs]e|fssai|batch|mfd|mfg|manufactured|marketed|packed|address|customer|contact|toll|feedback|taxes|mrp|nutrition|nutritional|serve|servings?|rda|quantity|enterprises?|industries|street|road|india)\b|@|\d+ ?g per 100|per 100 ?(?:g|ml)|numbering system|as per international/;
/** Abbreviations whose full stop doesn't end a sentence ("L. bulgaricus", "INS No. 330"). */
const NO_BREAK_BEFORE_DOT = new Set([
  'no',
  'nos',
  'vit',
  'approx',
  'min',
  'max',
  'ins',
  'st',
  'viz',
  'etc',
  'incl',
  'eg',
]);

function clean(raw: string): string {
  const s = raw
    .replace(/\b\d+(?:[.,]\d+)?\s*%/g, ' ')
    .replace(/\bmin(?:imum)?\.?\s/gi, ' ')
    .replace(/[*†‡^]+/g, ' ');
  return normName(s)
    .replace(/^allerg\w*(?: advice| information| info)? /, '')
    .replace(/^(?:contains?|and|or|with|incl|including) /, '')
    .replace(/ (?:and|or)$/, '')
    .trim();
}

const isSentenceEnd = (part: string, i: number) => {
  if (!/\s/.test(part.charAt(i + 1))) return false; // "2.5%"
  const token = /(\S+)$/.exec(part.slice(Math.max(0, i - 16), i))?.[1]?.toLowerCase() ?? '';
  if (!/^[a-z]+$/.test(token)) return token.length > 0; // "2%." or "(4%)." end a sentence
  return token.length >= 3 && !NO_BREAK_BEFORE_DOT.has(token);
};

/** Splits an ingredient list into candidates: each top-level ingredient plus its bracketed parts. */
export function splitCandidates(text: string): Candidate[] {
  const out: Candidate[] = [];
  const label = /^\s*ingredients?\s*[:-]?\s*/i.exec(text);
  let item = 0;

  const walk = (part: string, base: number, depth: number, parentItem: number | null) => {
    let d = 0;
    let segStart = 0;
    const segments: [number, number][] = [];
    for (let i = 0; i < part.length; i++) {
      const c = part.charAt(i);
      if (c === '(' || c === '[' || c === '{') d++;
      else if ((c === ')' || c === ']' || c === '}') && d > 0) d--;
      else if (d === 0 && (c === ',' || c === ';' || (c === '.' && isSentenceEnd(part, i)))) {
        segments.push([segStart, i]);
        segStart = i + 1;
      }
    }
    segments.push([segStart, part.length]);

    for (const [s, e] of segments) {
      const seg = part.slice(s, e);
      const itemIndex = parentItem ?? item++;
      let main = '';
      let depthInSeg = 0;
      let groupStart = -1;
      for (let j = 0; j < seg.length; j++) {
        const ch = seg.charAt(j);
        if (ch === '(' || ch === '[' || ch === '{') {
          if (depthInSeg === 0) groupStart = j + 1;
          depthInSeg++;
        } else if ((ch === ')' || ch === ']' || ch === '}') && depthInSeg > 0) {
          depthInSeg--;
          if (depthInSeg === 0 && groupStart >= 0) {
            if (depth < 2) walk(seg.slice(groupStart, j), base + s + groupStart, depth + 1, itemIndex);
            groupStart = -1;
          }
        } else if (depthInSeg === 0) main += ch;
      }
      const cleaned = clean(main);
      // "Emulsifier: soy lecithin" → "soy lecithin". Keep the whole name when nothing or only a
      // list of classes would remain ("Emulsifier", "Emulsifiers and flour treatment agent").
      const rest = stripClass(cleaned);
      const name = rest && !/^(?:and|or)\b/.test(rest) ? rest : cleaned;
      const lead = seg.length - seg.trimStart().length;
      const start = base + s + lead;
      const end = base + e - (seg.length - seg.trimEnd().length);
      if (name && end > start) out.push({ text: main.trim().replace(/\s+/g, ' '), name, start, end, item: itemIndex });
    }
  };

  const offset = label ? label[0].length : 0;
  walk(text.slice(offset), offset, 0, null);
  return out.filter(
    (c) =>
      !isTraceContext(text, c.start) &&
      !/^(?:allerg\w*(?: advice| information| info)? )?may contains?\b/.test(c.name) &&
      !NOISE.test(c.name) &&
      c.name.split(' ').length <= 8 &&
      // Something has to look like a word, a code or a vitamin ("a14", "06 j" are label debris).
      !ROMAN.test(c.name) &&
      (/[a-z]{3}/.test(c.name) || isCodeList(c.name) || VITAMIN.test(c.name) || ABBR.has(c.name)),
  );
}

// ---------- Knowing ----------

const MODIFIERS = new Set(
  (
    'dried dehydrated roasted toasted organic natural refined edible iodised iodized fresh frozen ground powdered whole ' +
    'pure raw cooked concentrated reconstituted pasteurised pasteurized sweetened unsweetened salted unsalted flaked chopped ' +
    'sliced diced crushed smoked fortified enriched permitted added extra virgin cold pressed instant premium selected fine ' +
    'coarse mixed assorted processed prepared liquid dry spray cultured fermented sprouted split skinned blanched peeled ' +
    'grated minced shredded puffed baked hydrolysed hydrolyzed low fat reduced full cream toned double skimmed common ' +
    'nature identical artificial synthetic certified active treated filtered purified clarified desiccated candied ' +
    'big small large baby sweet sour mild black white red green yellow brown golden dark light'
  ).split(' '),
);
const SUFFIXES = new Set(
  (
    'powder powders flour extract extracts oil paste puree juice pulp concentrate flakes pieces bits granules crystals ' +
    'solids essence seasoning blend mix syrup sauce leaves leaf seeds seed kernels oleoresin emulsion preparation filling ' +
    'coating cream base chunks crumbs substances substance agent agents salt salts'
  ).split(' '),
);
/** Vitamins written as letters/numbers ("B12", "vitamin D3", "vit. C"). */
const VITAMIN = /^(?:(?:vit|vitamin|vitamins) )?(?:a|b|c|d|e|k|h|pp|b ?\d{1,2}|d ?[23]|k ?[12])$/;
/** An additive code, possibly with a roman suffix written straight on ("501i" for 501(i)). */
const CODE_TOKEN = /^(?:ins|e)?\d{3,4}[a-h]?(?:i{1,3}|iv|vi?)?$/;
const ROMAN = /^(?:i{1,3}|iv|vi{0,3}|ix|x)$/;

/** The word and its likely singular forms ("preservatives" → "preservative", "tomatoes" → "tomato"). */
const forms = (w: string): string[] => {
  const out = [w];
  if (w.length > 3 && w.endsWith('s')) out.push(w.slice(0, -1));
  if (w.length > 4 && w.endsWith('es')) out.push(w.slice(0, -2));
  return out;
};
const singular = (w: string) => forms(w).at(-1) ?? w;
const inVocab = (w: string) => forms(w).some((f) => VOCAB.has(f)) || ADDITIVE_BY_NAME.has(w);
const isClass = (s: string) => forms(s).some((f) => CLASSES.has(f));

/** "ins 412", "e 150 d", "471 and 322" → ["e412"], ["e150d"], ["e471", "e322"]; [] if anything else is in there. */
function codesIn(name: string): string[] {
  const joined = name.replace(/\b(ins|e) (?=\d)/g, '$1').replace(/\b(\d{3,4}) ([a-h])\b/g, '$1$2');
  const tokens = joined.split(' ').filter((t) => !['and', 'or', 'i', 'ii', 'iii', 'iv', 'v', 'vi'].includes(t));
  if (!tokens.length || !tokens.every((t) => CODE_TOKEN.test(t))) return [];
  return tokens.map((t) => `e${t.replace(/^(?:ins|e)/, '').replace(/(\d)(?:i{1,3}|iv|vi?)$/, '$1')}`);
}
const isCodeList = (name: string) => codesIn(name).length > 0;
/** A code we know, allowing OCR's "4501" for "450(i)". */
const knownCode = (code: string) =>
  additiveInfo(code) != null || (/^e\d{4}$/.test(code) && code.endsWith('1') && additiveInfo(code.slice(0, 4)) != null);

/** The name without leading modifiers ("roasted") or trailing forms ("powder"). */
export function coreName(name: string): string {
  let words = name.split(' ').filter((w) => !STOP.has(w));
  while (words.length > 1 && MODIFIERS.has(words[0] ?? '')) words = words.slice(1);
  while (words.length > 1 && SUFFIXES.has(words.at(-1) ?? '')) words = words.slice(0, -1);
  return words.join(' ');
}

/** Strips a leading additive class ("acidity regulator citric acid" → "citric acid"). */
function stripClass(name: string): string {
  const words = name.split(' ');
  for (let n = Math.min(5, words.length); n >= 1; n--) {
    if (isClass(words.slice(0, n).join(' '))) return words.slice(n).join(' ');
  }
  return name;
}

function knownPart(name: string): boolean {
  if (!name || STOP.has(name) || isClass(name)) return true;
  const codes = codesIn(name);
  if (codes.length) return codes.every(knownCode);
  if (VITAMIN.test(name) || inVocab(name) || ABBR.has(name)) return true;
  const words = name.split(' ').filter((w) => !STOP.has(w));
  // Only qualifiers left ("natural", "nature identical", "substances" after a class name).
  if (words.every((w) => MODIFIERS.has(w) || SUFFIXES.has(w))) return true;
  // Strip forms one at a time: "black salt powder" → "black salt" (known) before "black".
  for (let n = words.length - 1; n >= 1 && SUFFIXES.has(words[n] ?? ''); n--) {
    if (inVocab(words.slice(0, n).join(' '))) return true;
  }
  const core = coreName(name);
  if (inVocab(core)) return true;
  const coreWords = core.split(' ');
  return (
    coreWords.length > 1 &&
    coreWords.every(
      (w) => inVocab(w) || MODIFIERS.has(w) || SUFFIXES.has(w) || ABBR.has(w) || VITAMIN.test(w) || CODE_TOKEN.test(w),
    )
  );
}

/** True when we know what this ingredient is (food, additive, abbreviation, vitamin or class name). */
export function isKnownName(name: string): boolean {
  if (knownPart(name)) return true;
  const rest = stripClass(name);
  if (rest !== name && knownPart(rest)) return true;
  // Lists joined by "and"/"or": "riboflavin and b12", "antioxidant and food colour".
  return [name, rest].some((n) => {
    const parts = n.split(/ (?:and|or) /).filter(Boolean);
    return parts.length > 1 && parts.every((p) => knownPart(p) || knownPart(stripClass(p)));
  });
}

/** Additive codes named by a candidate: written as codes, by additive name, or by abbreviation. */
export function additiveCodesFor(name: string): string[] {
  const rest = stripClass(name);
  for (const n of [name, rest]) {
    const codes = codesIn(n);
    if (codes.length) return codes;
    const abbr = ABBR.get(n);
    if (abbr?.code) return [abbr.code];
    const code = ADDITIVE_BY_NAME.get(n) ?? ADDITIVE_BY_NAME.get(coreName(n)) ?? ADDITIVE_BY_NAME.get(singular(n));
    if (code) return [code];
  }
  return [];
}

export interface AbbreviationUse {
  abbr: string;
  meaning: string;
  code?: string | undefined;
}

export interface IngredientReading {
  candidates: Candidate[];
  /** Candidates not explained by the vocabulary, additive dictionary or an exact rule match. */
  unknown: Candidate[];
  additiveCodes: Set<string>;
  abbreviations: AbbreviationUse[];
}

/**
 * Reads an ingredient list. `covered` are spans already matched exactly by a rule; any
 * candidate overlapping one counts as understood.
 */
export function readIngredients(text: string, covered: readonly { start: number; end: number }[]): IngredientReading {
  const candidates = splitCandidates(text);
  const additiveCodes = new Set<string>();
  const abbreviations = new Map<string, AbbreviationUse>();
  const unknown: Candidate[] = [];

  for (const c of candidates) {
    for (const code of additiveCodesFor(c.name)) additiveCodes.add(code);
    for (const key of new Set([c.name, ...c.name.split(' ')])) {
      const a = ABBR.get(key);
      if (!a) continue;
      if (!abbreviations.has(key))
        abbreviations.set(key, { abbr: key.toUpperCase(), meaning: a.meaning, code: a.code });
      if (a.code) additiveCodes.add(a.code);
    }
    const overlapsRule = covered.some((m) => m.start < c.end && m.end > c.start);
    if (!overlapsRule && !isKnownName(c.name)) unknown.push(c);
  }
  return { candidates, unknown, additiveCodes, abbreviations: [...abbreviations.values()] };
}

// ---------- Typo tolerance ----------

const VOCAB_FUZZY = new FuzzyIndex<true>();
for (const w of [...VOCAB, ...MODIFIERS, ...SUFFIXES]) if (!w.includes(' ')) VOCAB_FUZZY.add(w, true);
const ADDITIVE_FUZZY = new FuzzyIndex<string>();
for (const [name, code] of ADDITIVE_BY_NAME) ADDITIVE_FUZZY.add(name, code);

/** The additive code a misspelt additive name probably means ("carboxymethylcelulose" → e466). */
export function fuzzyAdditive(name: string): string | null {
  return ADDITIVE_FUZZY.find(name)?.value ?? ADDITIVE_FUZZY.find(coreName(name))?.value ?? null;
}

/** True when every word is a known ingredient word, allowing small typos ("tumeric", "lodised"). */
export function fuzzyKnown(name: string): boolean {
  const words = stripClass(name)
    .split(' ')
    .filter((w) => !STOP.has(w) && !MODIFIERS.has(w) && !SUFFIXES.has(w));
  return words.length > 0 && words.every((w) => inVocab(w) || CODE_TOKEN.test(w) || VOCAB_FUZZY.find(w) != null);
}
