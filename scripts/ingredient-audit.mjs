// Ingredient coverage audit: how much of ~500 real product labels Nouri understands, and the
// most common ingredients it doesn't recognise. `npm run audit:ingredients`
// Writes docs/INGREDIENT-COVERAGE.md. Review the "Not recognised" list: add harmless ones to
// extraVocabulary.ts and anything worth flagging to rules.ts.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { createServer } from 'vite';

const root = fileURLToPath(new URL('..', import.meta.url));
const server = await createServer({ root, server: { middlewareMode: true }, appType: 'custom', logLevel: 'error' });
try {
  const { measureCoverage, isHoldout, isForeignLabel } = await server.ssrLoadModule('/tests/ingredientCoverage.ts');
  const sample = JSON.parse(
    readFileSync(new URL('../tests/fixtures/off-ingredient-sample.json', import.meta.url), 'utf8'),
  );
  const { source } = sample;
  const products = sample.products.filter((p) => !isForeignLabel(p.ingredients));
  const foreign = sample.products.length - products.length;
  const all = measureCoverage(products);
  const reviewed = measureCoverage(products.filter((p) => !isHoldout(p.code)));
  const holdout = measureCoverage(products.filter((p) => isHoldout(p.code)));
  const pct = (x) => `${(x * 100).toFixed(1)}%`;

  const rows = [
    ['All', all],
    ['Review set', reviewed],
    ['Check set', holdout],
  ]
    .map(([label, s]) => `| ${label} | ${s.products} | ${s.ingredients} | ${pct(s.rate)} | ${pct(s.fullyRecognised)} |`)
    .join('\n');
  // Only the review set's misses are listed, so the check set keeps measuring how well fixes generalise.
  const top = reviewed.top
    .slice(0, 60)
    .map((t) => `| ${t.name} | ${t.count} | ${t.example.replace(/\|/g, '/')} |`)
    .join('\n');

  const md = `# Ingredient coverage

Generated by \`npm run audit:ingredients\` from ${products.length} popular real products with English labels
(mostly India, plus the UK and US). ${foreign} more products with labels in other languages were left out,
because Nouri's rules are written for English labels.
Sample: ${source}.

| Set | Products | Ingredients | Recognised | Products fully recognised |
|---|---|---|---|---|
${rows}

"Recognised" means the ingredient is matched by a scoring rule, the Open Food Facts ingredient or
additive dictionary, a label abbreviation, or Nouri's extra vocabulary (allowing small typos).
Unrecognised ingredients are listed in the app and never earn a bonus.

Products are split by barcode into a **review set** and a **check set**. Fixes should come only from the
review set's list below; the check set shows whether they carry over to labels nobody looked at. (In the
first round, v2.1.0, misses from both sets were reviewed, so the check set is a sanity check, not a blind test,
for those fixes.)

## Most common unrecognised ingredients (review set)

| Ingredient | Products | Example product |
|---|---|---|
${top || '| (none) | | |'}
`;
  writeFileSync(new URL('../docs/INGREDIENT-COVERAGE.md', import.meta.url), md);
  console.log(
    `recognised ${pct(all.rate)} of ${all.ingredients} ingredients (check set ${pct(holdout.rate)}); ${all.top.length} distinct unknowns`,
  );
  for (const t of reviewed.top.slice(0, 40)) console.log(`${String(t.count).padStart(3)}  ${t.name}`);
} finally {
  await server.close();
}
